-- HOW TO MODIFY THE VIEW DEFINITION?
ALTER VIEW vwRobotics
AS
SELECT STDID, STDNAME, STDAGE, STDGENDER FROM tblStudents WHERE STDCOURSE = 'ROBOTICS'
WITH CHECK OPTION


-- HOW TO REMOVE THE VIEW FROM THE DATABASE?
DROP VIEW vwRobotics


