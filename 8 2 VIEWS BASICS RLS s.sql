-- REQ 1:	HOW TO REPORT COMPUTERS STUDENTS?		 
SELECT * FROM tblStudents WHERE STDCOURSE = 'COMPUTERS'


-- REQ 2:	HOW TO STORE ABOVE QUERY IN THE DATABASE SO THAT WE CAN GIVE ACCESS TO ONLY COMPUTERS STAFF MEMBERS? 
CREATE VIEW vwComputers
AS
SELECT * FROM tblStudents WHERE STDCOURSE = 'COMPUTERS'
WITH CHECK OPTION


-- REQ 3:	HOW TO PERFORM SELECT OPERATIONS ON A VIEW?
SELECT * FROM vwComputers


-- REQ 4:	HOW TO PERFORM INSERT OPERATIONS ON A VIEW?
INSERT INTO vwComputers VALUES (2001, 'AMIN', 50, 'M', 'COMPUTERS')	-- NO ERROR. THIS ROW WILL BE INSERTED INTO THE TABLE.

INSERT INTO vwComputers VALUES (2002, 'AMIN', 50, 'M', 'CIVIL')		-- ERROR. REASON: COURSE NAME DOES NOT MATCH WITH VIEW CONDITION

SELECT * FROM tblStudents


-- REQ 5:	HOW TO PERFORM  UPDATE OPERATIONS ON A VIEW?
UPDATE vwComputers SET STDAGE = 0		-- ONLY COMPUTERS DATA IS UPDATED IN THE TABLE
SELECT * FROM tblStudents


-- REQ 6:	HOW TO PERFORM  DELETE OPERATIONS ON A VIEW?
DELETE FROM vwComputers					-- ONLY COMPUTERS DATA IS DELETED FROM THE TABLE. REMAINING DATA IS NOT AFFECTED.


-- REQ 7: VERIFY THE TABLE DATA AFTER DML OPERATIONS ON THE TABLE USING VIEW?
SELECT * FROM tblStudents
 

-- ONE MORE EXAMPLE:
CREATE VIEW vwRobotics
AS
SELECT * FROM tblStudents WHERE STDCOURSE = 'ROBOTICS'
WITH CHECK OPTION


SELECT * FROM vwRobotics

UPDATE vwRobotics SET StdAge = 100
SELECT * FROM tblStudents					-- WE SEE THAT ONLY ROBOTICS DATA IS UPDATED IN THE ACTUAL TABLE. 


DELETE FROM vwRobotics
SELECT * FROM tblStudents					-- WE SEE THAT ONLY ROBOTICS DATA IS DELETED IN THE ACTUAL TABLE. 


INSERT INTO vwRobotics VALUES (3001, 'AMINA', 50, 'F', 'ROBOTICS')	-- NO ERROR. THIS ROW WILL BE INSERTED INTO THE TABLE.
