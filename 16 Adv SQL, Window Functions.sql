-- REQUIREMENT : HOW TO RANK THE DATA? HOW TO IMPLEMENT WINDOW FUNCTIONS (RANK FUNCTIONS)?
-- PURPOSE OF WINDOW FUNCTIONS: TO HELP US ANALYSE THE DATA EASILY. 

/* IMPORTANT WINDOW FUNCTIONS: 
1. ROW_NUMBER()	:	THIS FUNCTION GENERATES A UNIQUE SEQUENCE OF VALUES.
					ONE SEQUENCE VALUE FOR EACH ROW.						EX: 1, 2, 3, 4.... 

2. RANK()		:	THIS FUNCTION GENERATES SAME SEQUENCE FOR SAME VALUE OF A GIVEN COLUMN. 
					NEXT VALUE OF THE COLUMN GENERATES ITS ROW NUMBER.		EX: 1, 1, 3, 3... 

3. DENSE_RANK()	:	THIS FUNCTION GENERATES SAME SEQUENCE FOR SAME VALUE OF A GIVEN COLUMN. 
					NEXT VALUE OF COLUMN GENERATES NEXT SEQUENCE NUMBER.	EX: 1, 1, 2, 2,... 
						 
4. PARTITION BY:	THIS KEYWORD GENERATES UNIQUE SEQUENCE FOR SAME VALUES OF A GIVEN COLUMN.
					NEXT VALUE OF COLUMN RESULTS IN RESET OF THE SEQUENCE.	EX: 1, 2, 1, 2,3, 1, 2

5. LAG	:			THIS SYSTEM FUNCTION REPORTS PREVIOUS VALUE OF A GIVEN COLUMN

6. LEAD	:			THIS SYSTEM FUNCTION REPORTS NEXT VALUE OF A GIVEN COLUMN
*/ 

SELECT *, ROW_NUMBER() OVER (ORDER BY Measure) SEQ1 FROM tblInventory						-- UNIQUE SEQUENCE

SELECT *, RANK() OVER (ORDER BY Measure) SEQ2 FROM tblInventory								-- JUMP IN SEQUENCE

SELECT *, DENSE_RANK() OVER (ORDER BY Measure) SEQ3 FROM tblInventory						-- EX: FLAGS FOR EACH TRANSACTION TYPE

SELECT *, ROW_NUMBER() OVER (PARTITION BY Measure ORDER BY Measure) SEQ4 FROM tblInventory	-- EX: SEQUENCE FOR EACH TRANSACTION TYPE

SELECT *, LAG(MEASURE) OVER (ORDER BY ID) PREVIOUS_VALUE FROM tblInventory					-- PREVIOUS VALUE OF THE SPECIFIED COLUMN

SELECT *, LEAD(MEASURE) OVER (ORDER BY ID) NEXT_VALUE FROM tblInventory						-- NEXT VALUE OF THE SPECIFIED COLUMN


-- COMBINING ALL ABOVE WINDOW FUNCTIONS SIDE BY SIDE:
SELECT *,	ROW_NUMBER() OVER (ORDER BY Measure) SEQ1,
			RANK() OVER (ORDER BY Measure) SEQ2,
			DENSE_RANK() OVER (ORDER BY Measure) SEQ3,
			ROW_NUMBER() OVER (PARTITION BY Measure ORDER BY Measure) SEQ4 
FROM tblInventory
 

