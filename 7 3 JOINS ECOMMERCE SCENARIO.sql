-- QUERY 1: WRITE A QUERY TO REPORT LIST OF PRODUCTS, RESPECTIVE SALES? 
-- WE NEED TO COMPARE PRODUCTS_DATA TABLE AND SALES_DATA TABLE, REPORT MATCHING DATA. 
-- FOR THIS, WE NEED TO USE "INNER JOIN"
SELECT * FROM tblProducts 
INNER JOIN tblSales 
ON tblProducts.ProductID = tblSales.SaleProductID
  

-- QUERY 2: WRITE A QUERY TO REPORT LIST OF PRODUCTS WITH SALES, PRODUCTS WITHOUT SALES? 
-- MEANS, WE NEED TO REPORT MATCHING & MISSING DATA. FOR THIS, WE USE "OUTER JOIN"
SELECT * FROM tblProducts 
LEFT OUTER JOIN tblSales		-- ALL LEFT. MATCHING RIGHT. NON MATCH RIGHT: NULL
ON tblProducts.ProductID = tblSales.SaleProductID


-- QUERY 3: WRITE A QUERY TO REPORT LIST OF PRODUCTS WITH SALES, PRODUCTS WITHOUT SALES? 
-- MEANS, WE NEED TO REPORT MATCHING & MISSING DATA. FOR THIS, WE USE "OUTER JOIN"
SELECT * FROM tblProducts 
RIGHT OUTER JOIN tblSales		-- ALL RIGHT. MATCHING LEFT. NON MATCH LEFT: NULL
ON tblProducts.ProductID = tblSales.SaleProductID



-- QUERY 4: WRITE A QUERY TO REPORT LIST OF PRODUCTS WITH SALES & WITHOUT SALES, VICE VERSA?  
SELECT * FROM tblProducts 
FULL OUTER JOIN tblSales		-- COMBINED OUTPUT OF LEFT OUTER JOIN & RIGHT OUTER JOIN
ON tblProducts.ProductID = tblSales.SaleProductID









